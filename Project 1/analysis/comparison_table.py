"""
Comparison Table — ingest every *_summary.json under data/results/live/
and emit a tidy markdown table of (suite × model) → accuracy.

Run from `Project 1/`:
    python analysis/comparison_table.py
or with --filter to limit suites:
    python analysis/comparison_table.py --filter hierarchy,adversarial

Output is also written to analysis/findings/RESULTS_TABLE.md so it can be
linked from FINDINGS_LOG.md without rerunning the script.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, List, Tuple

PROJECT_ROOT = Path(__file__).resolve().parent.parent
RESULTS_DIR = PROJECT_ROOT / "data" / "results" / "live"
FINDINGS_DIR = PROJECT_ROOT / "analysis" / "findings"


def collect() -> Dict[Tuple[str, str], Dict]:
    """Return {(experiment, model) -> latest summary}."""
    by_key: Dict[Tuple[str, str], Dict] = {}
    for path in sorted(RESULTS_DIR.glob("*_summary.json")):
        try:
            d = json.loads(path.read_text())
        except json.JSONDecodeError:
            continue
        # Skip smart-evaluator re-scoring files (they have a different shape)
        if "by_difficulty" in d:
            continue
        # Skip per-experiment summary files that don't carry an 'overall'
        # block (counting-curve, phrasing-probe — they live in their own
        # report files).
        if "overall" not in d:
            continue
        exp = d.get("experiment")
        model = d.get("model")
        if not exp or not model:
            continue
        # Keep the latest by timestamp
        existing = by_key.get((exp, model))
        if existing is None or d.get("timestamp", "") > existing.get("timestamp", ""):
            by_key[(exp, model)] = d
    return by_key


def render_markdown(table: Dict[Tuple[str, str], Dict], suites_filter: List[str] = None) -> str:
    suites = sorted({k[0] for k in table.keys()})
    models = sorted({k[1] for k in table.keys()})
    if suites_filter:
        suites = [s for s in suites if any(f in s for f in suites_filter)]

    out = ["# Cross-Model Comparison", "",
           "_Auto-generated by `analysis/comparison_table.py` from "
           "`data/results/live/*_summary.json`. Re-run any time._", ""]

    out.append("## Accuracy")
    header = "| Suite | n | " + " | ".join(models) + " |"
    out.append(header)
    out.append("|" + "---|" * (2 + len(models)))
    for s in suites:
        cells = []
        # Use the n from any model that ran this suite
        ns = [table[(s, m)]['overall']['n'] for m in models if (s, m) in table]
        n_str = str(ns[0]) if ns else "—"
        cells.append(s)
        cells.append(n_str)
        for m in models:
            cell = table.get((s, m))
            if cell is None:
                cells.append("—")
            else:
                acc = cell['overall']['accuracy']
                cells.append(f"{acc:.1%}")
        out.append("| " + " | ".join(cells) + " |")

    out.append("")
    out.append("## Latency (avg ms / trial)")
    out.append("| Suite | " + " | ".join(models) + " |")
    out.append("|" + "---|" * (1 + len(models)))
    for s in suites:
        cells = [s]
        for m in models:
            cell = table.get((s, m))
            if cell is None:
                cells.append("—")
            else:
                cells.append(f"{cell['overall']['avg_latency_ms']:.0f}")
        out.append("| " + " | ".join(cells) + " |")

    out.append("")
    out.append("## Token Volume (input / output)")
    out.append("| Suite | " + " | ".join(models) + " |")
    out.append("|" + "---|" * (1 + len(models)))
    for s in suites:
        cells = [s]
        for m in models:
            cell = table.get((s, m))
            if cell is None:
                cells.append("—")
            else:
                tin = cell['overall']['total_input_tokens']
                tout = cell['overall']['total_output_tokens']
                cells.append(f"{tin}/{tout}")
        out.append("| " + " | ".join(cells) + " |")

    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--filter', help='comma-separated suite name substrings to include')
    parser.add_argument('--write', action='store_true',
                        help='write to analysis/findings/RESULTS_TABLE.md')
    args = parser.parse_args()
    table = collect()
    suites_filter = args.filter.split(',') if args.filter else None
    md = render_markdown(table, suites_filter)
    print(md)
    if args.write:
        out = FINDINGS_DIR / "RESULTS_TABLE.md"
        out.write_text(md)
        print(f"\nwrote {out}", file=sys.stderr)


if __name__ == '__main__':
    main()
